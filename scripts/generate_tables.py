def _fmt_single_ratio(r: float) -> str:
    return f"${_fmt_ratio_value(r)}\\times$"


def generate_jena_macros() -> str:
    """Speedup macros for the Jena TDB2 comparison, if results exist.

    Emits both an all-scales range (dominated by the smallest scale,
    where Jena's fixed HTTP overhead versus SFDB's sub-millisecond
    in-process calls swamps any architectural signal) and a
    largest-scale-only point estimate (the scale at which the
    LOOKUP/GLOBAL-vs-CONTEXT/TEMPORAL crossover the paper discusses is
    actually visible), so prose citing the crossover at $10^5$ facts
    does not have to hand-transcribe a number out of the range.
    """
    path = REPO_ROOT / "results" / "jena_reference.json"
    if not path.exists():
        return (
            "% results/jena_reference.json not found; Jena macros left as (unknown).\n"
            "\\providecommand{\\jenaavailable}{false}\n"
        )
    data = json.loads(path.read_text())
    classes = ("LOOKUP", "GLOBAL", "CONTEXT", "TEMPORAL", "TEMPORAL_UNBOUNDED")
    macro_names = {
        "LOOKUP": "rangelookupjena",
        "GLOBAL": "rangeglobaljena",
        "CONTEXT": "rangecontextjena",
        "TEMPORAL": "rangetemporaljena",
        "TEMPORAL_UNBOUNDED": "rangetemporalunbjena",
    }
    large_macro_names = {
        "LOOKUP": "lookupjenalarge",
        "GLOBAL": "globaljenalarge",
        "CONTEXT": "contextjenalarge",
        "TEMPORAL": "temporaljenalarge",
        "TEMPORAL_UNBOUNDED": "temporalunbjenalarge",
    }
    all_scales = data.get("scales", {})
    scales = sorted((int(n) for n in all_scales), reverse=True)
    largest_scale_str = str(scales[0]) if scales else None
    largest_scale = all_scales.get(largest_scale_str, {}) if largest_scale_str else {}
    lines = [
        "% Auto-generated by scripts/generate_tables.py from results/jena_reference.json",
        "% Do not edit by hand. Ratios are jena_mean/sfdb_mean (above 1 = SFDB faster).",
        "% The *large macros are single-scale point estimates at the largest",
        "% scale measured, not ranges -- see the module docstring above.",
        "\\providecommand{\\jenaavailable}{true}",
        f"\\providecommand{{\\jenalargescale}}{{${largest_scale_str}$}}"
        if largest_scale_str
        else "\\providecommand{\\jenalargescale}{(unknown)}",
    ]
    for qclass in classes:
        ratios = []
        for entry in all_scales.values():
            e = entry.get(qclass)
            if e and e.get("sfdb_mean_ms"):
                ratios.append(e["jena_mean_ms"] / e["sfdb_mean_ms"])
        rng = _fmt_ratio_range(ratios) if ratios else "(unknown)"
        lines.append(f"\\providecommand{{\\{macro_names[qclass]}}}{{{rng}}}")

        large_entry = largest_scale.get(qclass)
        if large_entry and large_entry.get("sfdb_mean_ms"):
            large_ratio = large_entry["jena_mean_ms"] / large_entry["sfdb_mean_ms"]
            large_str = _fmt_single_ratio(large_ratio)
        else:
            large_str = "(unknown)"
        lines.append(f"\\providecommand{{\\{large_macro_names[qclass]}}}{{{large_str}}}")
    return "\n".join(lines) + "\n"


