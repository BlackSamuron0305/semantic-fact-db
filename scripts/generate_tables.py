def _fmt(x: float) -> str:
    if x < 1:
        return f"{x:.4f}"
    if x < 100:
        return f"{x:.2f}"
    return f"{x:,.1f}"


def _fmt_hw(x: float) -> str:
    """Format a 95% CI half-width compactly."""
    if x < 0.01:
        return f"{x:.3f}"
    if x < 1:
        return f"{x:.2f}"
    if x < 100:
        return f"{x:.1f}"
    return f"{x:,.0f}"


def _mean_ci(stats: dict) -> str:
    """Render mean with a 95% CI half-width, e.g. ``9.41 \\pm 0.12``."""
    mean = stats.get("mean", 0.0)
    hw = (stats.get("ci95_high", 0.0) - stats.get("ci95_low", 0.0)) / 2
    return f"{_fmt(mean)} \\pm {_fmt_hw(hw)}"


def _ratio(baseline: float, sfdb: float) -> str:
    if baseline == 0:
        return "n/a"
    r = sfdb / baseline
    if r >= 10:
        return f"{r:,.0f}\\times"
    return f"{r:.2f}\\times"


